// scripts/gen-rules-manifest.mjs — pins the rules hash into the shipped bundle.
//
// `computeRules()` reads source files with node:fs and cannot run in a browser,
// but the app must publish a rules hash in its commitment before turn 1. So the
// hash is computed here, at build time, and emitted as a constant the bundle can
// import.
//
// A generated constant is an assertion, and this project does not ship those:
// verify-ruleset R7 recomputes the hash from source and fails the build if the
// manifest has gone stale. Regenerate with `npm run gen:rules`.
import { writeFileSync } from 'node:fs';
import { computeRules } from '../lattice/ruleset.ts';

const { hash } = computeRules();
writeFileSync(
  new URL('../lattice/rules-manifest.ts', import.meta.url),
  `// GENERATED by scripts/gen-rules-manifest.mjs — do not edit.
//
// The rules hash of the sources listed in RULE_SOURCES, pinned so the browser
// bundle can publish it in a commitment without reading the filesystem.
// verify-ruleset R7 fails the build if this drifts from computeRules().

export const RULES_HASH = '${hash}';

/** The pinned rules hash. Named for symmetry with computeRules(). */
export function computeRulesFromManifest(): string {
  return RULES_HASH;
}
`,
);
console.log(`rules manifest pinned: ${hash}`);
